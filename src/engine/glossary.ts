/**
 * 한 설명 묶음 안에서 각 용어를 처음 쓸 때만 뜻을 붙여 주는 도우미.
 * 같은 패널 안에서 같은 설명이 반복되지 않도록 합니다.
 */
export class Glosser {
  private seen = new Set<string>();

  /**
   * 용어를 돌려줍니다. 처음 쓰는 용어면 "용어(뜻)" 형태로, 조사를 주면 조사는
   * 괄호 뒤에 붙이되 용어 자체에 맞춰 고릅니다. 예: t('프리플랍', '이/가') → "프리플랍(…)이".
   */
  t(term: string, pair?: JosaPair): string {
    const particle = pair ? josa(term, pair).slice(term.length) : '';
    const meaning = GLOSSARY[term];
    if (!meaning || this.seen.has(term)) return term + particle;
    this.seen.add(term);
    return `${term}(${meaning})${particle}`;
  }
}

/** 항상 뜻을 붙인 형태. 버튼 설명 등 짧은 곳에 씁니다. */
export function glossed(term: string): string {
  const meaning = GLOSSARY[term];
  return meaning ? `${term}(${meaning})` : term;
}
